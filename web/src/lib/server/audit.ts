const TITLE_RE = /<title[^>]*>([\s\S]*?)<\/title>/i;
const META_TAG_RE = /<meta\b[^>]*>/gi;
const ATTR_RE = /([\w:-]+)\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s"'>]*))/gi;
const YEAR_RE = /(?:©|&copy;|copyright)\s*(?:copyright)?\s*(\d{4})/gi;
const TAG_STRIP_RE = /<[^>]+>/g;
const SCRIPT_BLOCK_RE = /<(script|style|noscript)[^>]*>[\s\S]*?<\/\1>/gi;
const WS_RE = /\s+/g;
const IMG_COUNT_RE = /<img\b/gi;
const HTTP_ASSET_RE = /(?:src|href)\s*=\s*["']http:\/\/(?!www\.w3\.org|schemas)/gi;
