#!/usr/bin/env node
// Generates migrations/0004_seed_leads.sql from the pipeline's real leads.csv
// using the same engine functions the admin CSV import endpoint uses, so slug,
// template, theme and vertical derivation stay consistent between seed and
// import. Run from web/: node --experimental-strip-types tools/generate-lead-seed.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { csvToProspect, parseCsv } from '../src/lib/server/csvLeads.ts';
import {
  classifyIndustry,
  classifyProspectTheme,
  prospectHostnames,
  prospectSlug,
  recommendTemplate
} from '../src/lib/content/engine.ts';
import { matchVertical } from '../src/lib/verticals/taxonomy.ts';

const here = dirname(fileURLToPath(import.meta.url));
const csv = readFileSync(join(here, '..', '..', 'leads.csv'), 'utf8');

function sqlString(value) {
  return `'${String(value ?? '').replace(/'/g, "''")}'`;
}

const rows = parseCsv(csv);
const statements = [];
let skipped = 0;
const seen = new Set();

for (const row of rows) {
  const name = row['Business Name']?.trim();
  if (!name) {
    skipped++;
    continue;
  }
  // JSON columns and inline quoting mirror csvToProspect + upsertProspect.
  const prospect = csvToProspect(row);
  const slug = prospectSlug(prospect);
  if (seen.has(slug)) {
    throw new Error(`Duplicate slug derived for ${name}: ${slug}`);
  }
  seen.add(slug);
  const kind = classifyIndustry(prospect);
  const record = {
    id: slug,
    slug,
    name: prospect.name,
    industry: prospect.industry,
    industry_kind: kind,
    phone: prospect.phone,
    address: prospect.address,
    website: prospect.website,
    email: prospect.email,
    traffic_tier: prospect.traffic_tier,
    decision_maker: prospect.decision_maker,
    classification: prospect.classification,
    opportunity: prospect.opportunity,
    need_score: prospect.need_score,
    value_score: prospect.value_score,
    site_health: prospect.site_health,
    rating: prospect.rating,
    review_count: prospect.review_count,
    audit_summary: prospect.audit_summary,
    pitch_facts: JSON.stringify(prospect.pitch_facts ?? []),
    sources: JSON.stringify(prospect.sources ?? []),
    source_ids: prospect.source_ids,
    low_confidence: prospect.low_confidence ? 1 : 0,
    maps_url: prospect.maps_url,
    last_audited: prospect.last_audited,
    persona: prospect.persona,
    template: recommendTemplate(kind),
    theme: classifyProspectTheme(prospect, kind),
    vertical: matchVertical(prospect),
    hostnames: JSON.stringify(prospectHostnames(prospect)),
    indexable: 0,
    status: 'new'
  };
  const columns = Object.keys(record);
  const values = columns.map((c) => {
    const v = record[c];
    if (v === null || v === undefined) return 'NULL';
    if (typeof v === 'number') return String(v);
    return sqlString(v);
  });
  statements.push(
    `INSERT INTO businesses (${columns.join(', ')}) VALUES (${values.join(', ')}) ON CONFLICT(id) DO NOTHING;`
  );
}

const header = [
  '-- Seed: the real, scraped St. Louis County outreach leads from leads.csv.',
  '-- Generated by tools/generate-lead-seed.mjs; deterministic, do not hand-edit.',
  '-- Idempotent: rows that already exist keep their data (no overwrite).',
  '',
  ...statements,
  '',
  `-- ${statements.length} seeded lead rows; ${skipped} rows skipped (empty business name).`,
  ''
].join('\n');

const out = join(here, '..', 'migrations', '0004_seed_leads.sql');
writeFileSync(out, header);
console.log(`Wrote ${out}: ${statements.length} leads, ${skipped} skipped.`);
